# ---------------------------
# 1. Alle Datensätze bündeln
# ---------------------------
all_data <- list(
  Huh7 = Huh7
)

# ---------------------------
# 2. DataFrame erstellen
# ---------------------------
df <- imap_dfr(all_data, function(dataset, dataset_name) {
  imap_dfr(dataset, function(values, compound) {
    tibble(
      Dataset = dataset_name,
      Compound = compound,
      Wert = values
    )
  })
})

# ---------------------------
# 2a. Zu färbende Verbindungen
# ---------------------------
blue_compounds <- c(
  "c03", "c05", "c07", "c08", "c10",
  "c17", "c19", "c21", "c30",
  "c33", "c34", "c35", "c38", "c39", "c41", "c45", "c46",
  "c49", "c51", "c52", "c54", "c55", "c56", "c57", "c60", "c62", "c63",
  "c72"
)

df <- df %>%
  mutate(
    Highlight = if_else(
      Compound %in% blue_compounds,
      "Blue",
      "Red"
    )
  )

# ---------------------------
# 3. Reihenfolge nach Mittelwert
# ---------------------------
compound_order <- df %>%
  group_by(Compound) %>%
  summarise(mean_value = mean(Wert, na.rm = TRUE), .groups = "drop") %>%
  arrange(mean_value) %>%
  pull(Compound)

# Kontrolle immer links
compound_order <- c("ctrl", setdiff(compound_order, "ctrl"))

# Faktor-Reihenfolge setzen
df$Compound <- factor(df$Compound, levels = compound_order)

# ---------------------------
# 4. Hintergrundbereiche
# ---------------------------
bg <- data.frame(
  xmin = seq(0.5, length(compound_order) - 0.5, by = 2),
  xmax = seq(1.5, length(compound_order) + 0.5, by = 2),
  ymin = -Inf,
  ymax = Inf
)

# ---------------------------
# 5. Plot
# ---------------------------
ggplot(df, aes(x = Compound, y = Wert)) +
  
  # Hintergrund
  geom_rect(
    data = bg,
    inherit.aes = FALSE,
    aes(
      xmin = xmin,
      xmax = xmax,
      ymin = ymin,
      ymax = ymax
    ),
    fill = "grey80"
  ) +
  
  # Boxplots
  geom_boxplot(
    aes(fill = Highlight, colour = Highlight),
